-- QR / code-based digital warranty: product variants, generated codes, batches, event history.

-- 1. Product variants (one row per model + case/band + dial, keyed by the factory barcode).
create table public.watch_variants (
  barcode text primary key,
  model_no text not null,
  factory_no text not null,
  case_band text not null,
  dial text not null,
  qty_ordered integer not null default 0 check (qty_ordered >= 0),
  serial_seq integer not null default 0
);
create index watch_variants_model_idx on public.watch_variants (model_no);
grant select, insert, update, delete on public.watch_variants to authenticated; grant all on public.watch_variants to service_role;
alter table public.watch_variants enable row level security;
create policy "admins manage variants" on public.watch_variants for all to authenticated using (public.has_role(auth.uid(),'admin')) with check (public.has_role(auth.uid(),'admin'));

-- 2. Batches of generated warranty codes.
create table public.warranty_batches (
  id uuid primary key default gen_random_uuid(),
  variant_barcode text not null references public.watch_variants(barcode),
  qty integer not null check (qty > 0),
  created_by uuid,
  created_at timestamptz not null default now());
grant select on public.warranty_batches to authenticated; grant all on public.warranty_batches to service_role;
alter table public.warranty_batches enable row level security;
create policy "admins read batches" on public.warranty_batches for select to authenticated using (public.has_role(auth.uid(),'admin'));

-- 3. Unguessable activation codes: 12 characters, no 0/1/I/O, drawn from gen_random_uuid() random bytes.
create or replace function public.gen_warranty_code() returns text language plpgsql volatile set search_path = public as $$
declare
  alphabet constant text := '23456789ABCDEFGHJKLMNPQRSTUVWXYZ';
  b bytea := uuid_send(gen_random_uuid());
  i int;
  result text := '';
begin
  -- bytes 6 and 8 of a v4 uuid carry fixed version bits, so they are skipped
  foreach i in array array[0,1,2,3,4,5,9,10,11,12,13,14] loop
    result := result || substr(alphabet, (get_byte(b, i) & 31) + 1, 1);
  end loop;
  return result;
end $$;

alter table public.warranties
  add column code text not null unique default public.gen_warranty_code(),
  add column variant_barcode text references public.watch_variants(barcode),
  add column batch_id uuid references public.warranty_batches(id),
  add column owner_email text,
  add column expires_at timestamptz;
create index warranties_batch_idx on public.warranties (batch_id);
create index warranties_variant_idx on public.warranties (variant_barcode);
update public.warranties set expires_at = activated_at + interval '1 year' where activated_at is not null;

-- 4. Event history, written by trigger so every path is recorded.
create table public.warranty_events (
  id bigint generated always as identity primary key,
  warranty_id uuid not null references public.warranties(id) on delete cascade,
  type text not null,
  actor uuid,
  created_at timestamptz not null default now());
create index warranty_events_warranty_idx on public.warranty_events (warranty_id);
grant select on public.warranty_events to authenticated; grant all on public.warranty_events to service_role;
alter table public.warranty_events enable row level security;
create policy "admins read events" on public.warranty_events for select to authenticated using (public.has_role(auth.uid(),'admin'));

create or replace function public.log_warranty_event() returns trigger language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' then
    insert into public.warranty_events (warranty_id, type, actor) values (new.id, 'created', auth.uid());
  elsif new.status is distinct from old.status then
    insert into public.warranty_events (warranty_id, type, actor)
    values (new.id, case new.status when 'active' then 'activated' when 'void' then 'voided' else 'reset' end, auth.uid());
  end if;
  return new;
end $$;
revoke execute on function public.log_warranty_event() from public;
create trigger warranties_log after insert or update on public.warranties for each row execute function public.log_warranty_event();

-- 5. Staff: generate codes for one variant.
create or replace function public.create_warranty_batch(_barcode text, _qty integer) returns uuid language plpgsql security definer set search_path = public as $$
declare v public.watch_variants; first_no integer; b uuid;
begin
  if not public.has_role(auth.uid(), 'admin') then raise exception 'not authorised'; end if;
  if _qty is null or _qty < 1 or _qty > 5000 then raise exception 'quantity must be between 1 and 5000'; end if;
  update public.watch_variants set serial_seq = serial_seq + _qty where barcode = _barcode returning * into v;
  if not found then raise exception 'unknown variant %', _barcode; end if;
  first_no := v.serial_seq - _qty;
  insert into public.warranty_batches (variant_barcode, qty, created_by) values (_barcode, _qty, auth.uid()) returning id into b;
  insert into public.warranties (serial, model, variant_barcode, batch_id)
  select _barcode || '-' || lpad((first_no + n)::text, greatest(4, length((first_no + n)::text)), '0'), v.model_no, _barcode, b
  from generate_series(1, _qty) n;
  return b;
end $$;

-- Staff: generate everything still missing from the order for one model. Returns the number of codes created.
create or replace function public.create_model_batches(_model_no text) returns integer language plpgsql security definer set search_path = public as $$
declare r record; total integer := 0;
begin
  if not public.has_role(auth.uid(), 'admin') then raise exception 'not authorised'; end if;
  for r in select barcode, qty_ordered - serial_seq as missing from public.watch_variants where model_no = _model_no and qty_ordered > serial_seq order by barcode loop
    perform public.create_warranty_batch(r.barcode, r.missing);
    total := total + r.missing;
  end loop;
  return total;
end $$;

-- 6. Public lookup and activation by code (no owner details are ever returned).
drop function public.lookup_warranty(text);
drop function public.activate_warranty(text, text, text);

create or replace function public.normalize_warranty_code(_code text) returns text language sql immutable as $$
  select regexp_replace(upper(coalesce(_code, '')), '[^A-Z0-9]', '', 'g') $$;

create or replace function public.lookup_warranty(_code text)
returns table(serial text, model text, case_band text, dial text, status text, activated_at timestamptz, expires_at timestamptz)
language sql stable security definer set search_path = public as $$
  select w.serial, w.model, v.case_band, v.dial,
    case when w.status = 'active' and w.expires_at < now() then 'expired' else w.status end,
    w.activated_at, w.expires_at
  from public.warranties w left join public.watch_variants v on v.barcode = w.variant_barcode
  where w.code = public.normalize_warranty_code(_code) $$;

-- Result is one of: activated, invalid, not_found, active, void. The warranty runs one year from activation.
create or replace function public.activate_warranty(_code text, _name text, _email text, _phone text default null)
returns text language plpgsql security definer set search_path = public as $$
declare c text := public.normalize_warranty_code(_code); s text;
begin
  if length(trim(coalesce(_name, ''))) not between 2 and 120
    or trim(coalesce(_email, '')) !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' or length(trim(_email)) > 254
    or length(trim(coalesce(_phone, ''))) > 30 then return 'invalid'; end if;
  update public.warranties set status = 'active', owner_name = trim(_name), owner_email = lower(trim(_email)),
    owner_phone = nullif(trim(coalesce(_phone, '')), ''), activated_at = now(), expires_at = now() + interval '1 year'
  where code = c and status = 'pending';
  if found then return 'activated'; end if;
  select status into s from public.warranties where code = c;
  return coalesce(s, 'not_found');
end $$;

revoke execute on function public.create_warranty_batch(text, integer), public.create_model_batches(text) from public, anon;
grant execute on function public.create_warranty_batch(text, integer), public.create_model_batches(text) to authenticated;
grant execute on function public.lookup_warranty(text), public.activate_warranty(text, text, text, text) to anon, authenticated;

